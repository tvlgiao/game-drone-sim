/**
 * Vite plugin: after the build, writes dist/sw.js, a service worker that precaches every emitted file
 * (minus source maps, .well-known and the landing page screenshots) so the web game (/play/), its
 * installed PWA and the Meta Quest app (/app/, a Trusted Web Activity on this origin) play offline after
 * the first visit. It sits at the site root so one worker's scope covers every page.
 * The cache name is a hash of the file contents, so each deploy installs a fresh cache and drops the old.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

const SKIP = [/\.map$/, /^\.well-known\//, /^sw\.js$/, /^screenshots\//];

/**
 * The CC0 texture maps (albedo / normal / ARM WebP, ~6 MB): cached when a level first asks for them, not on
 * install. A level never visited offline falls back to its procedural sets (the material library's fallback).
 */
export const RUNTIME_ASSET_RE = /(^|\/)assets\/(albedo|normal|arm)-[\w-]+\.webp$/;

/**
 * The built files the worker precaches: the shell, the code chunks and workers, icons. Source maps, the app-link
 * files, the worker itself, screenshots and the runtime-cached texture maps are left out.
 */
export function precacheFiles(files: readonly string[]): string[] {
  return files.filter((f) => !SKIP.some((re) => re.test(f)) && !RUNTIME_ASSET_RE.test(f)).sort();
}

function walk(dir: string, root = dir, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, root, out);
    else out.push(relative(root, p).split(sep).join('/'));
  }
  return out;
}

/** Precache URLs: every file, plus each page's directory URL (`./play/` is how /play/index.html is requested). */
export function precacheUrls(files: readonly string[]): string[] {
  const pages = files.filter((f) => f === 'index.html' || f.endsWith('/index.html')).map((f) => `./${f.slice(0, -'index.html'.length)}`);
  return [...new Set([...pages, ...files.map((f) => `./${f}`)])];
}

/** The world engine's chunk worker as Vite emits it (`new URL('./world-worker.ts', import.meta.url)`). */
export const WORLD_WORKER_RE = /(^|\/)world-worker[-.][\w-]*\.js$/;

/**
 * Throws unless the chunk worker is in the precache: offline, a missing worker would push every chunk onto the
 * main thread (the inline fallback) without anyone noticing.
 */
export function assertWorkerPrecached(files: readonly string[]): void {
  if (!precacheUrls(files).some((u) => WORLD_WORKER_RE.test(u))) throw new Error('offline-sw: the world chunk worker (world-worker-*.js) is not in the precache list');
}

/** The worker source for a file list and version (exported for tests). */
export function swSource(files: readonly string[], version: string): string {
  return `/* generated by build/offline-sw.ts */
const CACHE = 'dronesim-${version}';
const RUNTIME = ${RUNTIME_ASSET_RE.toString()};
const FILES = ${JSON.stringify(precacheUrls(files))};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('dronesim-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // pages: network first so a new deploy shows up, the cached page when offline (query ignored:
    // /play/?xremu=1 is /play/), else the landing page
    e.respondWith(fetch(req).catch(() => caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((r) => r || caches.match('./', { ignoreVary: true }))));
    return;
  }
  // hashed assets, icons, manifest: cache first. ignoreVary: module scripts carry an Origin header the
  // precache requests did not, and hosts answer with Vary: Origin / Accept-Encoding
  if (RUNTIME.test(new URL(req.url).pathname)) {
    // texture maps: cache first too, filled on first use (same versioned cache, cleared with it)
    e.respondWith(
      caches.match(req, { ignoreSearch: true, ignoreVary: true }).then(
        (r) =>
          r ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              e.waitUntil(caches.open(CACHE).then((c) => c.put(req, copy)));
            }
            return res;
          }),
      ),
    );
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((r) => r || fetch(req)));
});
`;
}

export function offlineServiceWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'offline-sw',
    apply: 'build',
    configResolved(c) {
      outDir = c.build.outDir;
    },
    closeBundle() {
      const files = precacheFiles(walk(outDir));
      assertWorkerPrecached(files);
      const h = createHash('sha256');
      // the version follows every built file, the runtime-cached maps too (a new map clears the old cache)
      for (const f of walk(outDir).filter((x) => RUNTIME_ASSET_RE.test(x) || files.includes(x)).sort()) h.update(f).update(readFileSync(join(outDir, f)));
      writeFileSync(join(outDir, 'sw.js'), swSource(files, h.digest('hex').slice(0, 12)));
    },
  };
}
